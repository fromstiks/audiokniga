package ua.starky.audiokniga.playback

/**
 * Шаг перемотки, общий на весь процесс.
 *
 * Его читают три независимых места: экран книги, уведомление на замке и виджет на
 * рабочем столе. Держать его в трёх копиях — верный способ получить разные числа
 * на разных кнопках, поэтому значение живёт здесь, а настройки его обновляют.
 */
object SkipSettings {
    @Volatile
    var skipMs: Long = 20_000L

    val seconds: Int get() = (skipMs / 1000L).toInt()
}
